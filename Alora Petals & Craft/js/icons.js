/** Hasilkan markup <svg> untuk sebuah ikon.
 *  name   : nama ikon (mis. 'favorite', 'shopping_bag')
 *  cls    : class tambahan (ukuran/warna, mis. 'text-[18px] text-primary')
 *  filled : true = tampilan terisi (hanya berpengaruh pada ikon yang punya versi terisi, mis. hati) */
